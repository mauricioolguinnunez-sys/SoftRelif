class Lang:
    _current = "es"

    @classmethod
    def get(cls, key, **kwargs):
        text = TRANSLATIONS.get(cls._current, {}).get(key, key)
        if kwargs:
            text = text.format(**kwargs)
        return text

    @classmethod
    def set(cls, lang):
        if lang in ("es", "en"):
            cls._current = lang

    @classmethod
    def current(cls):
        return cls._current

    @classmethod
    def toggle(cls):
        cls._current = "en" if cls._current == "es" else "es"
        return cls._current
